"""The copy of the plugin's modules inside ``plugins/davi-route/lib``.

A marketplace install copies only ``plugins/davi-route``, so the plugin
carries the ``judge_adapter`` modules its hooks and ``davi-read`` import.
The copy is generated, never edited: ``davi-route bundle`` rewrites it and
``davi-route bundle --check`` (and a test) fails when it is stale.

Which modules: the ones loaded after importing ``ENTRY_MODULES`` in a fresh
interpreter (lazy imports of the hook path are listed there explicitly).
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from pathlib import Path

ENTRY_MODULES = (
    'judge_adapter.routing.hooks',
    'judge_adapter.routing.verifiers',
    # the davi-read command (hooks/davi_read.py)
    'judge_adapter.reading.cli',
    # imported inside functions on the hook path
    'judge_adapter.plugin_common',
    'judge_adapter.contract',
    'judge_adapter.core',
)
MARKER = 'BUNDLED.txt'
MARKER_TEXT = (
    'Generated by `davi-route bundle` from src/judge_adapter. Do not edit:\n'
    'change src/ and run `davi-route bundle` again.\n'
)
_LIST_MODULES = """
import importlib, json, sys
sys.path.insert(0, sys.argv[1])
for name in sys.argv[2:]:
    importlib.import_module(name)
files = [
    getattr(module, '__file__', None)
    for name, module in sys.modules.items()
    if name == 'judge_adapter' or name.startswith('judge_adapter.')
]
print(json.dumps(sorted(path for path in files if path)))
"""


class Bundle:
    """``src/judge_adapter`` (the source) and its copy in the plugin."""

    def __init__(self, repo_root=None):
        root = Path(repo_root or Path(__file__).resolve().parents[3])
        self._src = root / 'src'
        self._lib = root / 'plugins' / 'davi-route' / 'lib'

    @property
    def lib(self):
        return self._lib

    def wanted(self):
        """Relative paths (under ``src``) of the modules to bundle."""
        result = subprocess.run(
            [sys.executable, '-I', '-c', _LIST_MODULES, str(self._src)]
            + list(ENTRY_MODULES),
            capture_output=True,
            text=True,
            check=True,
            timeout=60,
        )
        src = self._src.resolve()
        return sorted(
            Path(path).resolve().relative_to(src).as_posix()
            for path in json.loads(result.stdout)
        )

    def stale(self):
        """Paths whose copy is missing, different or no longer wanted."""
        wanted = self.wanted()
        present = (
            sorted(
                path.relative_to(self._lib).as_posix()
                for path in self._lib.rglob('*.py')
            )
            if self._lib.is_dir()
            else []
        )
        problems = sorted(set(present) - set(wanted))
        for rel in wanted:
            copy = self._lib / rel
            if (
                not copy.is_file()
                or copy.read_bytes() != (self._src / rel).read_bytes()
            ):
                problems.append(rel)
        marker = self._lib / MARKER
        if not marker.is_file() or marker.read_text() != MARKER_TEXT:
            problems.append(MARKER)
        return problems

    def write(self):
        """Replace the copy with the current modules; returns their paths."""
        wanted = self.wanted()
        if self._lib.exists():
            shutil.rmtree(self._lib)
        for rel in wanted:
            target = self._lib / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(self._src / rel, target)
        (self._lib / MARKER).write_text(MARKER_TEXT)
        return wanted
